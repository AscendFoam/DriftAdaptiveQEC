    ends = starts + lengths
    candidates = _threshold_candidates()
    enter = np.asarray([row["regime_posterior_enter_min"] for row in candidates], dtype=np.float64)
    exit_threshold = np.asarray([row["regime_posterior_exit_max"] for row in candidates], dtype=np.float64)
    uncertainty = np.asarray([row["uncertainty_fallback_min"] for row in candidates], dtype=np.float64)
    ood_threshold = np.asarray([row["ood_score_min_code"] for row in candidates], dtype=np.int64)
    enter_hysteresis = np.asarray([row["enter_hysteresis_windows"] for row in candidates], dtype=np.int64)
